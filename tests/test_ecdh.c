/* The host suite for P-256 key agreement: p256_keygen and p256_ecdh,
 * which exist because OFTC will not take x25519 and asks for a P-256
 * share with a HelloRetryRequest (REQUIREMENTS.md 5.12).
 *
 * The vectors are from an independent oracle, the cryptography package,
 * generated once: two key pairs and the secret they agree, which is the
 * x coordinate of a*b*G. The family's rule: the host proves the
 * arithmetic before the machine measures it. */
#include <stdio.h>
#include <string.h>
#include "p256.h"

static int checks, failed;
#define CHECK(cond, what) do { checks++; if (!(cond)) { failed++; printf("FAIL line %d: %s\n", __LINE__, what); } } while (0)

/* Generated once from the cryptography package: two P-256 pairs and
 * their agreed secret, which is the x coordinate of a*b*G. */
static const uint8_t priv_a[32] = {
  0x86, 0xaa, 0x58, 0x28, 0x73, 0x91, 0x3c, 0xf8, 0x92, 0x4a, 0x9c, 0x84, 0xd0, 0xe3, 0xd5, 0x98,
  0x9d, 0x3a, 0xac, 0x99, 0x71, 0x92, 0xed, 0x04, 0xa3, 0xf3, 0x7e, 0x8a, 0x56, 0xf1, 0x81, 0x56,
};
static const uint8_t pub_a[64] = {
  0x51, 0x31, 0x27, 0x2a, 0x13, 0x54, 0x65, 0x55, 0xa5, 0x84, 0x2d, 0xc3, 0xca, 0x16, 0x75, 0x47,
  0x01, 0xb5, 0x3c, 0x41, 0xbb, 0xfc, 0x53, 0xa1, 0xf0, 0x8a, 0xb9, 0x9c, 0xd1, 0xe3, 0xd1, 0xa4,
  0x9d, 0xe9, 0x30, 0x3c, 0xb2, 0x74, 0x38, 0x5a, 0x6b, 0x16, 0x1c, 0xc2, 0xe8, 0x80, 0x45, 0x09,
  0x1a, 0x0a, 0x48, 0xa9, 0xb7, 0x4a, 0x86, 0xbe, 0x50, 0xb0, 0x7d, 0x9d, 0x41, 0xb8, 0xac, 0x6c,
};
static const uint8_t priv_b[32] = {
  0xbf, 0x4c, 0xbf, 0x81, 0xf4, 0x69, 0x5f, 0x92, 0xe1, 0xb8, 0x6a, 0x15, 0x52, 0x69, 0x52, 0xa5,
  0xee, 0x06, 0xdb, 0x28, 0xf6, 0x66, 0x6c, 0xdd, 0x57, 0xa1, 0xcf, 0x7e, 0x53, 0xf8, 0x25, 0x51,
};
static const uint8_t pub_b[64] = {
  0x04, 0x0f, 0x98, 0xde, 0xca, 0x69, 0x7b, 0x55, 0x55, 0xf4, 0xc2, 0x5d, 0x71, 0x93, 0x23, 0x33,
  0x0a, 0xce, 0x7e, 0x84, 0x21, 0x5a, 0x12, 0x74, 0x44, 0xf2, 0x27, 0x6f, 0xb2, 0xa5, 0xb6, 0x8f,
  0x94, 0x15, 0x1d, 0x01, 0x34, 0x5d, 0x44, 0x07, 0x76, 0xb9, 0xa7, 0x52, 0x67, 0x57, 0x21, 0x4d,
  0xad, 0x19, 0x54, 0xe8, 0x62, 0xbc, 0x70, 0x82, 0xd3, 0xb6, 0x1e, 0x2f, 0xf7, 0xda, 0x56, 0x54,
};
static const uint8_t shared_ab[32] = {
  0xa3, 0xc8, 0xf0, 0x2b, 0x7d, 0x82, 0xf4, 0xd5, 0xa6, 0xa3, 0x13, 0x8e, 0x47, 0x3d, 0xdb, 0x75,
  0x8c, 0x87, 0xd6, 0xf8, 0xab, 0xd7, 0x38, 0xa1, 0x75, 0x42, 0x47, 0x55, 0x52, 0x9a, 0x82, 0x6c,
};

int main(void)
{
  uint8_t pub[64], pub2[64], s[32], bad[64], zero[32], ones[32];

  /* the public keys the oracle derived from these scalars */
  CHECK(p256_keygen(pub, priv_a) && !memcmp(pub, pub_a, 64), "keygen a: the oracle's public key, x and y");
  CHECK(p256_keygen(pub, priv_b) && !memcmp(pub, pub_b, 64), "keygen b: likewise");

  /* the agreed secret, from either side */
  CHECK(p256_ecdh(s, priv_a, pub_b) && !memcmp(s, shared_ab, 32), "a with b's key: the oracle's secret");
  CHECK(p256_ecdh(s, priv_b, pub_a) && !memcmp(s, shared_ab, 32), "b with a's key: the same secret");

  /* the failures */
  memcpy(bad, pub_b, 64); bad[63] ^= 1;
  CHECK(!p256_ecdh(s, priv_a, bad), "a point off the curve is refused, not multiplied");
  memset(zero, 0, 32);
  CHECK(!p256_keygen(pub, zero), "a zero scalar is refused");
  CHECK(!p256_ecdh(s, zero, pub_b), "and refused for agreement");
  memset(ones, 0xff, 32);
  CHECK(p256_keygen(pub, ones), "a scalar above n is reduced and used");

  /* no hidden state: the same scalar gives the same key twice running */
  p256_keygen(pub, priv_a); p256_keygen(pub2, priv_a);
  CHECK(!memcmp(pub, pub2, 64), "keygen is a function of its scalar alone");

  /* the shape TLS carries: 04, X, Y, 65 bytes; the x coordinate is the secret */
  CHECK(shared_ab[0] == 0xa3, "the secret is the raw x coordinate, not hashed");

  printf("%d checks, %d failed\n", checks, failed);
  return failed != 0;
}
